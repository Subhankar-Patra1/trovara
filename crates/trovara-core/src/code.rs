/// The repo (or code project) `path` is in, and the file's title: its path from the repo's folder, the repo's name
/// first ("billing/payments/retry.py"). Outside any: its folder's name and its own.
pub fn place(path: &Path) -> (Option<String>, String) {
    let home = std::env::var_os("USERPROFILE").map(PathBuf::from);
    let mut folder = path.parent();
    while let Some(here) = folder {
        if here.parent().is_none() || home.as_deref().is_some_and(|home| same_path(home, here)) {
            break;
        }
        if is_repo(here) {
            let parent_length = here.parent().map_or(0, |p| p.as_os_str().len());
            let text = path.to_string_lossy();
            let title = text[parent_length.min(text.len())..].trim_start_matches(['\\', '/']).replace('\\', "/");
            return (Some(here.to_string_lossy().into_owned()), title);
        }
        folder = here.parent();
    }
    let parts: Vec<String> = path
        .components()
        .filter_map(|c| match c {
            std::path::Component::Normal(part) => Some(part.to_string_lossy().into_owned()),
            _ => None,
        })
        .collect();
    (None, parts[parts.len().saturating_sub(2)..].join("/"))
}

/// A folder that's a repo (a `.git` in it) or a code project (Cargo.toml, package.json, a .sln…).
pub fn is_repo(folder: &Path) -> bool {
    if folder.join(".git").exists() {
        return true;
    }
    let Ok(entries) = std::fs::read_dir(folder) else { return false };
    let names: Vec<String> = entries.flatten().map(|e| e.file_name().to_string_lossy().into_owned()).collect();
    crate::rules::is_project_root(names.iter().map(String::as_str))
}

fn same_path(a: &Path, b: &Path) -> bool {
    a.to_string_lossy().trim_end_matches(['\\', '/']).eq_ignore_ascii_case(b.to_string_lossy().trim_end_matches(['\\', '/']))
}

/// "Swift", "Python", "Markdown": what a file's extension says it's written in.
pub fn language(path: &Path) -> String {
    let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let extension = path.extension().and_then(|e| e.to_str()).unwrap_or_default().to_ascii_lowercase();
    if let Some((_, language)) = LANGUAGES.iter().find(|(ext, _)| *ext == extension) {
        return language.to_string();
    }
    if crate::rules::CODE_FILE_NAMES.contains(&name.as_str()) || name.starts_with("Dockerfile") {
        return name;
    }
    if extension.is_empty() {
        "Text".into()
    } else {
        extension.to_ascii_uppercase()
    }
}

