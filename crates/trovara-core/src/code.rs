/// The words keyword search keeps a name from code as ("quantize_row_q8_0_ref" → quantize row q8 0 ref, as one
/// phrase), when the query is one: snake_case, camelCase, dotted, or with digits. None for words anyone would say
/// ("retry", "Renamer"), which are searched as words and by meaning.
pub fn identifier(query: &str) -> Option<Vec<String>> {
    let mut name = query.trim();
    if let Some(stripped) = name.strip_suffix("()") {
        name = stripped;
    }
    if !is_name_path(name) {
        return None;
    }
    let camel = name.chars().skip(1).any(char::is_uppercase) && name.chars().any(char::is_lowercase);
    if !camel && !name.chars().any(|c| "_.:#$".contains(c) || c.is_ascii_digit()) {
        return None;
    }
    Some(
        name.to_lowercase()
            .split(|c: char| !c.is_alphanumeric())
            .filter(|word| !word.is_empty())
            .map(str::to_string)
            .collect(),
    )
}

/// `^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$`
fn is_name_path(name: &str) -> bool {
    let bytes = name.as_bytes();
    let mut i = 0;
    loop {
        // One name.
        match bytes.get(i) {
            Some(b) if b.is_ascii_alphabetic() || *b == b'_' || *b == b'$' => i += 1,
            _ => return false,
        }
        while bytes.get(i).is_some_and(|b| b.is_ascii_alphanumeric() || *b == b'_' || *b == b'$') {
            i += 1;
        }
        if i == bytes.len() {
            return true;
        }
        // Then a separator.
        let rest = &name[i..];
        let step = if rest.starts_with("::") || rest.starts_with("->") {
            2
        } else if rest.starts_with('.') || rest.starts_with('#') {
            1
        } else {
            return false;
        };
        i += step;
    }
}

/// The keyword search pattern for an identifier's words: one phrase, so they match only side by side, as written.
pub fn phrase(words: &[String]) -> String {
    format!("\"{}\"", words.join(" "))
}

const DEFINERS: &[&str] = &[
    "def", "func", "fn", "fun", "function", "class", "struct", "enum", "protocol", "interface", "trait", "type",
    "typealias", "actor", "extension", "impl", "module", "namespace", "object", "record", "macro", "const", "let",
    "var", "val", "union", "mod", "sub", "@interface", "@implementation", "@protocol", "#define", "function*",
];
/// Words before a name that mean it's being used, not defined ("await name(…)", "return name(…)").
const USERS: &[&str] = &[
    "return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and", "or", "in",
    "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise", "import", "from",
];
/// How comments and docstrings start.
const COMMENT_STARTS: &[&str] = &["//", "#", "/*", "*", "--", "\"\"\"", "'''", "<!--", ";"];

/// A word that starts a definition ("def", "func", "class", "@implementation"…).
pub fn defines_something(word: &str) -> bool {
    DEFINERS.contains(&word) && !["let", "var", "const", "val"].contains(&word)
}

/// Where `name` is defined in `text` (a stretch whose first line is `first`): the line, and how surely. 2 after a
/// word that defines something (def, func, class, function, struct, #define, @implementation…) or as a C-style
/// definition (a type before it, its parameters after it, no "=" or call around it); 1 for a declaration (the same,
/// ending in ";"). None when the stretch only uses it.
pub fn definition(name: &str, text: &str, first: usize) -> Option<(usize, u8)> {
    let mut best: Option<(usize, u8)> = None;
    for (offset, line) in split_lines(text).into_iter().enumerate() {
        for (start, end) in occurrences(name, line) {
            let before = line[..start].trim();
            let after = line[end..].trim();
            let strength = definition_strength(before, after, line);
            if strength > best.map_or(0, |b| b.1) {
                best = Some((first + offset, strength));
            }
            if strength == 2 {
                return best;
            }
        }
    }
    best
}

fn definition_strength(before: &str, after: &str, line: &str) -> u8 {
    let previous = before.split_whitespace().last().unwrap_or_default();
    if DEFINERS.contains(&previous) {
        return 2;
    }
    if before.starts_with("func (") && before.ends_with(')') {
        return 2; // a Go method
    }
    if before.starts_with("- (") || before.starts_with("+ (") {
        // An Objective-C method.
        return if after.starts_with(':') || after.is_empty() || after.starts_with('{') || after.starts_with(';') {
            2
        } else {
            0
        };
    }
    // C-style: "static void name(…) {", "struct gguf_context * name(…)", not a call or an assignment.
    let last = before.chars().last();
    if !after.starts_with('(')
        || before.is_empty()
        || USERS.contains(&previous)
        || before.chars().any(|c| "=(,.!?".contains(c))
        || before.contains("->")
        || !last.is_some_and(|c| c.is_alphanumeric() || "*&>_]".contains(c))
    {
        return 0;
    }
    if line.trim().ends_with(';') {
        1
    } else {
        2
    }
}

/// The line (from `first`) to open at for `words`: the first line with one of them that defines something ("def
/// retry_with_backoff"), else the first such line of code (not a comment), else the first such line. A word counts as
/// itself or as a part of a name (the "retry" of retryWithBackoff and retry_with_backoff). None when none is there.
pub fn first_line(words: &[String], text: &str, first: usize) -> Option<usize> {
    let words: Vec<Vec<char>> =
        words.iter().filter(|w| w.chars().count() >= 2).map(|w| w.to_lowercase().chars().collect()).collect();
    if words.is_empty() {
        return None;
    }
    let (mut first_code, mut first_any) = (None, None);
    for (offset, line) in split_lines(text).into_iter().enumerate() {
        if !words.iter().any(|word| has(word, line)) {
            continue;
        }
        let trimmed = line.trim_matches([' ', '\t']);
        if trimmed.split_whitespace().take(4).any(defines_something) {
            return Some(first + offset);
        }
        if first_code.is_none() && !COMMENT_STARTS.iter().any(|start| trimmed.starts_with(start)) {
            first_code = Some(offset);
        }
        if first_any.is_none() {
            first_any = Some(offset);
        }
    }
    first_code.or(first_any).map(|offset| first + offset)
}

/// Whether `line` has `word` (lowercased) as a word or as the start of a name's part.
fn has(word: &[char], line: &str) -> bool {
    let original: Vec<char> = line.chars().collect();
    // One lowercase character per character, so places line up with the original's.
    let lower: Vec<char> = original.iter().map(|c| c.to_lowercase().next().unwrap_or(*c)).collect();
    if word.len() > lower.len() {
        return false;
    }
    (0..=lower.len() - word.len()).any(|at| {
        lower[at..at + word.len()] == *word
            // A word or a name's part starts here: at the line's start, after something that isn't a letter or a
            // digit, or at a capital letter (camelCase).
            && (at == 0 || !lower[at - 1].is_alphanumeric() || original[at].is_uppercase())
    })
}

/// Where `name` is in `line` as a whole name (not a part of a longer one), whatever its case: byte ranges.
fn occurrences(name: &str, line: &str) -> Vec<(usize, usize)> {
    let is_name = |c: char| c.is_alphanumeric() || c == '_' || c == '$';
    let (haystack, needle) = (line.to_ascii_lowercase(), name.to_ascii_lowercase());
    let mut found = Vec::new();
    if needle.is_empty() {
        return found;
    }
    let mut from = 0;
    while let Some(at) = haystack[from..].find(&needle) {
        let (start, end) = (from + at, from + at + needle.len());
        let clear_before = line[..start].chars().next_back().is_none_or(|c| !is_name(c));
        let clear_after = line[end..].chars().next().is_none_or(|c| !is_name(c));
        if clear_before && clear_after {
            found.push((start, end));
        }
        from = end;
    }
    found
}

#[cfg(test)]
