//! Code for the code index (TRD §6.6): a source file, a repo's doc or a notebook, cut into stretches of whole lines (a
//! notebook's into whole cells) that the model reads one at a time, each knowing where it is, so that a result opens
//! there. And names in code (`lookup`): a query that's a name finds it exactly, at the place that defines it rather
//! than every place that uses it.

use std::path::{Path, PathBuf};

/// A stretch of a file: its text, and its first and last lines (or cells), from 1.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Piece {
    pub text: String,
    pub first: usize,
    pub last: usize,
}

#[derive(Clone, Debug)]
pub struct CodeFile {
    pub pieces: Vec<Piece>,
    /// For the model, the file's title: its path in its repo ("payments/retry.py" in the "billing" repo reads
    /// "billing/payments/retry.py"), which says more about code than its name alone (the reference's real-code eval:
    /// the name alone had 22 vs 24 of 27 in the top 5).
    pub title: String,
    /// The repo (or code project) it's in, if any.
    pub repo: Option<String>,
    pub lines: usize,
    /// A notebook's cells (code and notes; outputs are never read). None for anything else.
    pub cells: Option<usize>,
}

/// Why a code file isn't read.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CodeError {
    /// Read, and not worth indexing: made by a program, minified, a key in it, not text.
    LeftOut(String),
    Unreadable(String),
}

impl std::fmt::Display for CodeError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            CodeError::LeftOut(why) => f.write_str(why),
            CodeError::Unreadable(why) => write!(f, "unreadable: {why}"),
        }
    }
}

impl std::error::Error for CodeError {}

/// The model reads 2,048 tokens of an input at most; a single line longer than this is cut here.
pub const LONGEST_PIECE: usize = 4000;

/// Reads a code file: its stretches, title and repo. `max_bytes`: a notebook's cells over it were written by a program.
pub fn read(path: &Path, stretch: usize, max_bytes: u64) -> Result<CodeFile, CodeError> {
    let data = std::fs::read(path).map_err(|e| CodeError::Unreadable(e.to_string()))?;
    let (repo, title) = place(path);
    let is_notebook = path.extension().is_some_and(|e| e.eq_ignore_ascii_case("ipynb"));
    if is_notebook {
        let cells = notebook_cells(&data)?;
        let text = cells.join("\n");
        // As for any code: more than this was written by a program (data pasted into a cell).
        if text.len() as u64 > max_bytes {
            return Err(CodeError::LeftOut(format!("cells over {} MB", max_bytes >> 20)));
        }
        check(&text, true)?;
        return Ok(CodeFile {
            pieces: self::cells(&cells, stretch),
            title,
            repo,
            lines: line_count(&text),
            cells: Some(cells.len()),
        });
    }
    if data[..data.len().min(8000)].contains(&0) {
        return Err(CodeError::LeftOut("not text".into()));
    }
    let text = match String::from_utf8(data) {
        Ok(text) => text,
        // Not UTF-8: Latin-1, as the reference reads it (every byte is a character).
        Err(error) => error.into_bytes().iter().map(|&b| b as char).collect(),
    };
    let text = text.strip_prefix('\u{FEFF}').unwrap_or(&text).to_string();
    let extension = path.extension().and_then(|e| e.to_str()).unwrap_or_default().to_ascii_lowercase();
    check(&text, crate::rules::SOURCE_EXTENSIONS.contains(&extension.as_str()))?;
    Ok(CodeFile { pieces: lines(&text, stretch), title, repo, lines: line_count(&text), cells: None })
}

/// Code that's no use to read: it holds a private key, or (`source`: code, not a repo's notes) a program wrote it (its
/// generator says so at the top: "DO NOT EDIT", "@generated") or it's minified.
pub fn check(text: &str, source: bool) -> Result<(), CodeError> {
    if text.contains("PRIVATE KEY-----") {
        return Err(CodeError::LeftOut("holds a private key".into()));
    }
    if !source {
        return Ok(());
    }
    let top: String = text.chars().take(1000).collect();
    for mark in ["DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by", "Generated by the protocol"] {
        if top.contains(mark) {
            return Err(CodeError::LeftOut(format!("made by a program (“{mark}”)")));
        }
    }
    // Minified: few lines, and long ones (a bundle can be one line of 100,000 characters).
    let lines = line_count(text).max(1);
    let characters = text.chars().count();
    if characters / lines > 300 && text.split('\n').any(|line| line.chars().count() > 3000) {
        return Err(CodeError::LeftOut(format!("minified ({} characters a line)", characters / lines)));
    }
    Ok(())
}

pub fn line_count(text: &str) -> usize {
    let count = text.bytes().filter(|&b| b == b'\n').count();
    if text.ends_with('\n') || text.is_empty() {
        count
    } else {
        count + 1
    }
}

/// The lines of `text`: "\n" and "\r\n" both end a line, as they do in an editor.
fn split_lines(text: &str) -> Vec<&str> {
    text.split('\n').map(|line| line.strip_suffix('\r').unwrap_or(line)).collect()
}

/// Lines that close a block (shell, Ruby, Lua, Objective-C, the C preprocessor).
const CLOSERS: &[&str] = &["end", "fi", "done", "esac", "@end", "#endif", "end;", "end)"];

/// Stretches of whole lines, each at most `size` characters (a longer line is a stretch of its own). A stretch ends,
/// when it can, where the code does: before a line that starts a new block at the left margin, or after a blank line,
/// in its last 60%. One that had to stop in the middle of a block hands its last two lines on to the next, so whatever
/// spans the cut is read whole once.
pub fn lines(text: &str, size: usize) -> Vec<Piece> {
    let mut lines = split_lines(text);
    if lines.last().is_some_and(|line| line.is_empty()) {
        lines.pop(); // the final newline
    }
    let count = lines.len();
    let mut offsets = Vec::with_capacity(count + 1); // characters before each line (each with its newline)
    offsets.push(0usize);
    for line in &lines {
        offsets.push(offsets.last().unwrap() + line.chars().count() + 1);
    }
    let blank = |index: usize| lines[index].chars().all(char::is_whitespace);
    let starts_block = |index: usize| {
        let Some(first) = lines[index].chars().next() else { return false };
        if first.is_whitespace() {
            return false;
        }
        // A closing line belongs to the block above it.
        !"})]".contains(first) && !CLOSERS.contains(&lines[index].trim())
    };

    let mut pieces = Vec::new();
    let mut start = 0;
    while start < count {
        while start < count && blank(start) {
            start += 1;
        }
        if start >= count {
            break;
        }
        let mut end = start + 1; // the stretch is lines[start..end]
        while end < count && offsets[end + 1] - offsets[start] <= size {
            end += 1;
        }
        let mut natural = end >= count;
        if !natural {
            // Where the code breaks by itself, keeping at least 40% of a stretch: a new block after a blank line first,
            // then any blank line or new block.
            let floor = offsets[start] + size * 2 / 5;
            let last_break = |is_break: &dyn Fn(usize) -> bool| {
                let mut line = end;
                while line > start + 1 && offsets[line] >= floor {
                    if is_break(line) {
                        return Some(line);
                    }
                    line -= 1;
                }
                None
            };
            let cut = last_break(&|line| starts_block(line) && blank(line - 1))
                .or_else(|| last_break(&|line| blank(line - 1) || starts_block(line)));
            if let Some(cut) = cut {
                end = cut;
                natural = true;
            }
        }
        let mut last = end;
        while last > start + 1 && blank(last - 1) {
            last -= 1; // blank lines at its end don't count
        }
        let mut body = lines[start..last].join("\n");
        if body.chars().count() > LONGEST_PIECE {
            body = body.chars().take(LONGEST_PIECE).collect();
        }
        pieces.push(Piece { text: body, first: start + 1, last });
        start = if natural { end } else { end.saturating_sub(2).max(start + 1) };
    }
    pieces
}

/// A stretch in one line, for result lists: its first line that defines something ("def retry_with_backoff(…"), else
/// its first line of code (not a comment, an import or a closing brace).
pub fn summary(text: &str) -> String {
    let lines: Vec<&str> = split_lines(text).into_iter().map(|line| line.trim_matches([' ', '\t'])).filter(|l| !l.is_empty()).collect();
    let definition = lines.iter().find(|line| line.split_whitespace().take(4).any(defines_something));
    let code = lines.iter().find(|line| {
        !["//", "#", "/*", "*", "--", "\"\"\"", "import ", "from ", "#include", "using ", "package ", "}", ")", "@"]
            .iter()
            .any(|prefix| line.starts_with(prefix))
    });
    let line = definition.or(code).or(lines.first()).copied().unwrap_or_default();
    if line.chars().count() > 160 {
        line.chars().take(160).collect::<String>() + "…"
    } else {
        line.to_string()
    }
}

// MARK: Notebooks

/// The cells of a Jupyter notebook, code and notes alike, as their text. Outputs (pictures, tables, logs) aren't read:
/// they're results, not what anyone wrote.
pub fn notebook_cells(data: &[u8]) -> Result<Vec<String>, CodeError> {
    let notebook: serde_json::Value =
        serde_json::from_slice(data).map_err(|_| CodeError::Unreadable("not a notebook".into()))?;
    if !notebook.is_object() {
        return Err(CodeError::Unreadable("not a notebook".into()));
    }
    // nbformat 4 keeps its cells at the top; nbformat 3 inside worksheets, with code in "input".
    let cells = notebook["cells"]
        .as_array()
        .or_else(|| notebook["worksheets"].get(0).and_then(|w| w["cells"].as_array()))
        .cloned()
        .unwrap_or_default();
    Ok(cells
        .iter()
        .map(|cell| {
            let source = if cell.get("source").is_some() { &cell["source"] } else { &cell["input"] };
            match source {
                serde_json::Value::Array(parts) => parts.iter().filter_map(|p| p.as_str()).collect(),
                serde_json::Value::String(text) => text.clone(),
                _ => String::new(),
            }
        })
        .collect())
}

/// Whole cells to a stretch, up to `size` characters; a longer cell is cut into stretches of lines that all point at
/// it. Empty cells are passed over.
pub fn cells(cells: &[String], size: usize) -> Vec<Piece> {
    let mut pieces = Vec::new();
    let (mut text, mut first, mut last) = (String::new(), 0, 0);
    let flush = |text: &mut String, first: usize, last: usize, pieces: &mut Vec<Piece>| {
        if !text.is_empty() {
            pieces.push(Piece { text: std::mem::take(text), first, last });
        }
    };
    for (index, cell) in cells.iter().enumerate() {
        let body = cell.trim();
        if body.is_empty() {
            continue;
        }
        let number = index + 1;
        let length = body.chars().count();
        if length > size {
            flush(&mut text, first, last, &mut pieces);
            pieces.extend(lines(body, size).into_iter().map(|p| Piece { text: p.text, first: number, last: number }));
            continue;
        }
        if !text.is_empty() && text.chars().count() + 2 + length > size {
            flush(&mut text, first, last, &mut pieces);
        }
        if text.is_empty() {
            first = number;
            text = body.to_string();
        } else {
            text.push_str("\n\n");
            text.push_str(body);
        }
        last = number;
    }
    flush(&mut text, first, last, &mut pieces);
    pieces
}

